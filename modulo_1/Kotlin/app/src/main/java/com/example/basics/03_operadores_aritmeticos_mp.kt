package com.example.basics

fun main(){
    println("¡OPERADORES ARITMÉTICOS - TALLER MECÁNICO!")

    val costoManoObra: Double = 25.8
    val costoRepuesto: Double = 3.8

    println("Costo total (suma): ${costoManoObra + costoRepuesto} USD")
    println("Diferencia de costos (resta): ${costoManoObra - costoRepuesto} USD")
    println("Costo por 3 reparaciones (multiplicación): ${costoManoObra * 3}")
    println("Promedio de costo por pieza (división): ${costoManoObra / costoRepuesto}")
}
