void main() {
  print("Operaciones Aritmeticas - Tema: Taller Mecanico");

  final double costoAceite = 25.5;
  final double costoFiltro = 15.0;

  print("Suma: Aceite + Filtro = ${costoAceite + costoFiltro}");
  print("Resta: Aceite - Filtro = ${costoAceite - costoFiltro}");
  print("Multiplicacion: Aceite x 2 = ${costoAceite * 2}");
  print("Division: Costo total / 2 = ${(costoAceite + costoFiltro) / 2}");
}
